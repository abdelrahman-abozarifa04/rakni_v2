import 'package:flutter/material.dart';
import 'package:flutter_svg/flutter_svg.dart';
import 'package:rakni_v2/core/services/firestore_service.dart';
import 'package:rakni_v2/core/theme/app_colors.dart';
import 'package:rakni_v2/core/models/vehicle_model.dart';
import 'package:rakni_v2/core/utils/validators.dart';
import 'package:rakni_v2/features/main/main_shell.dart';

class AddCarScreen2 extends StatefulWidget {
  final String? uid;

  const AddCarScreen2({super.key, this.uid});

  @override
  State<AddCarScreen2> createState() => _AddCarScreen2State();
}

class _AddCarScreen2State extends State<AddCarScreen2> {
  bool _isLoading = false;

  final TextEditingController _brandController = TextEditingController();
  final TextEditingController _plateController = TextEditingController();
  final TextEditingController _modelController = TextEditingController();
  final TextEditingController _colorController = TextEditingController();

  @override
  void dispose() {
    _brandController.dispose();
    _plateController.dispose();
    _modelController.dispose();
    _colorController.dispose();
    super.dispose();
  }

  void _showSnackBar(String message) {
    if (!mounted) return;
    ScaffoldMessenger.of(context).showSnackBar(
      SnackBar(
        content: Text(message),
        backgroundColor: Colors.redAccent,
        behavior: SnackBarBehavior.floating,
        shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(10)),
      ),
    );
  }

  Future<void> _addCar() async {
    final brand = _brandController.text.trim();
    final plate = _plateController.text.trim();
    final model = _modelController.text.trim();
    final color = _colorController.text.trim();

    if (brand.isEmpty || plate.isEmpty || model.isEmpty || color.isEmpty) {
      _showSnackBar('Please fill in all fields.');
      return;
    }
    final plateError = Validators.validateEgyptianPlate(plate);
    if (plateError != null) {
      _showSnackBar(plateError);
      return;
    }

    setState(() => _isLoading = true);

    try {
      // Save car data if uid is provided (registration flow)
      if (widget.uid != null) {
        await FirestoreService().addVehicle(
          widget.uid!,
          VehicleModel(
            id: '', // ID will be generated by Firestore
            brand: brand,
            plateNumber: plate,
            model: model,
            color: color,
            isDefault: true,
          ),
        );
      }

      if (!mounted) return;
      Navigator.pushAndRemoveUntil(
        context,
        MaterialPageRoute(builder: (context) => const MainShell()),
        (route) => false,
      );
    } catch (e) {
      _showSnackBar(e.toString().replaceFirst('Exception: ', ''));
    } finally {
      if (mounted) setState(() => _isLoading = false);
    }
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      backgroundColor: AppColors.background,
      appBar: AppBar(
        backgroundColor: Colors.transparent,
        elevation: 0,
        leading: IconButton(
          icon: const Icon(
            Icons.arrow_back_ios_new,
            color: AppColors.white,
            size: 20,
          ),
          onPressed: () => Navigator.pop(context),
        ),
      ),
      body: SafeArea(
        child: SingleChildScrollView(
          padding: const EdgeInsets.symmetric(horizontal: 24.0),
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.stretch,
            children: [
              // ── Header Icon ──────────────────────────────────
              Center(
                child: Container(
                  height: 100,
                  width: 100,
                  decoration: BoxDecoration(
                    color: AppColors.fieldColor,
                    shape: BoxShape.circle,
                  ),
                  child: Center(
                    child: SvgPicture.asset(
                      'assets/images/car_Icon.svg',
                      height: 70,
                      colorFilter: const ColorFilter.mode(
                        AppColors.secondary,
                        BlendMode.srcIn,
                      ),
                    ),
                  ),
                ),
              ),
              const SizedBox(height: 24),

              // ── Title & Subtitle ─────────────────────────────
              const Text(
                'Add Your Car',
                textAlign: TextAlign.center,
                style: TextStyle(
                  color: AppColors.white,
                  fontSize: 24,
                  fontWeight: FontWeight.w600,
                ),
              ),
              const SizedBox(height: 8),
              const Text(
                'Enter your vehicle details',
                textAlign: TextAlign.center,
                style: TextStyle(color: AppColors.textSecondary, fontSize: 15),
              ),
              const SizedBox(height: 32),

              // ── Form Fields ──────────────────────────────────
              _buildLabel('Car Brand'),
              _buildTextField(
                controller: _brandController,
                hintText: 'e.g., Toyota, BMW, Mercedes',
              ),
              const SizedBox(height: 20),
              _buildLabel('Plate Number'),
              _buildTextField(
                controller: _plateController,
                hintText: 'e.g. أبج١٢٣٤ or ABC1234',
              ),

              const SizedBox(height: 20),
              _buildLabel('Model'),
              _buildTextField(
                controller: _modelController,
                hintText: 'e.g., Camry, Civic, X5',
              ),

              const SizedBox(height: 20),
              _buildLabel('Color'),
              _buildTextField(
                controller: _colorController,
                hintText: 'e.g., Black, Silver, White',
              ),
              const SizedBox(height: 60),

              // ── Bottom Button ───────────────────────────────
              ElevatedButton(
                onPressed: _isLoading ? null : _addCar,
                style: ElevatedButton.styleFrom(
                  backgroundColor: AppColors.secondary,
                  foregroundColor: AppColors.primary,
                  shape: RoundedRectangleBorder(
                    borderRadius: BorderRadius.circular(14),
                  ),
                  minimumSize: const Size(double.infinity, 56),
                  elevation: 0,
                ),
                child: _isLoading
                    ? const SizedBox(
                        height: 20,
                        width: 20,
                        child: CircularProgressIndicator(
                          strokeWidth: 2,
                          color: AppColors.primary,
                        ),
                      )
                    : const Text(
                        'Add Car',
                        style: TextStyle(
                          fontSize: 16,
                          fontWeight: FontWeight.w700,
                        ),
                      ),
              ),
              const SizedBox(height: 24),
            ],
          ),
        ),
      ),
    );
  }

  Widget _buildLabel(String text) {
    return Padding(
      padding: const EdgeInsets.only(bottom: 8.0, left: 4),
      child: Text(
        text,
        style: const TextStyle(
          color: AppColors.white,
          fontSize: 15,
          fontWeight: FontWeight.w500,
        ),
      ),
    );
  }

  Widget _buildTextField({
    required TextEditingController controller,
    required String hintText,
  }) {
    return TextField(
      controller: controller,
      style: const TextStyle(color: AppColors.white, fontSize: 14),
      decoration: InputDecoration(
        hintText: hintText,
        hintStyle: const TextStyle(color: AppColors.hintColor, fontSize: 14),
        filled: true,
        fillColor: AppColors.fieldColor,
        contentPadding: const EdgeInsets.symmetric(
          vertical: 18,
          horizontal: 16,
        ),
        border: OutlineInputBorder(
          borderRadius: BorderRadius.circular(12),
          borderSide: const BorderSide(color: AppColors.fieldStroke),
        ),
        enabledBorder: OutlineInputBorder(
          borderRadius: BorderRadius.circular(12),
          borderSide: const BorderSide(color: AppColors.fieldStroke),
        ),
        focusedBorder: OutlineInputBorder(
          borderRadius: BorderRadius.circular(12),
          borderSide: const BorderSide(color: AppColors.secondary, width: 1.5),
        ),
      ),
    );
  }
}
